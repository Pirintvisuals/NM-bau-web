  function norm(s) { return s.replace(/\s+/g, ' ').trim(); }

  var snaps = [];
  function takeSnapshot() {
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (!n.nodeValue || !norm(n.nodeValue)) return NodeFilter.FILTER_REJECT;
        var p = n.parentNode ? n.parentNode.nodeName : '';
        if (p === 'SCRIPT' || p === 'STYLE' || p === 'NOSCRIPT') return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = walker.nextNode())) snaps.push({ kind: 'text', node: n, hu: n.nodeValue });

    var attrs = ['placeholder', 'aria-label', 'title', 'data-words'];
    document.querySelectorAll('[placeholder],[aria-label],[title],[data-words]').forEach(function (el) {
      attrs.forEach(function (a) {
        if (el.hasAttribute(a)) snaps.push({ kind: 'attr', node: el, attr: a, hu: el.getAttribute(a) });
      });
    });
    snaps.push({ kind: 'title', hu: document.title });
  }

  function translate(lang, hu) {
    var t = DICT[lang];
    if (!t) return null;
    var v = t[norm(hu)];
    return (v === undefined) ? null : v;
  }

  function apply(lang) {
    snaps.forEach(function (s) {
      if (s.kind === 'title') {
        document.title = (lang === 'hu') ? s.hu : (translate(lang, s.hu) || s.hu);
        return;
      }
      if (lang === 'hu') {
        if (s.kind === 'text') s.node.nodeValue = s.hu;
        else s.node.setAttribute(s.attr, s.hu);
        return;
      }
      var tr = translate(lang, s.hu);
      if (s.kind === 'text') {
        var lead = (s.hu.match(/^\s*/) || [''])[0];
        var trail = (s.hu.match(/\s*$/) || [''])[0];
        s.node.nodeValue = (tr === null) ? s.hu : (lead + tr + trail);
      } else {
        s.node.setAttribute(s.attr, tr === null ? s.hu : tr);
      }
    });
    document.documentElement.lang = lang;
    document.querySelectorAll('.lang-btn').forEach(function (b) {
      var on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('active', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
    try { localStorage.setItem('nmlang', lang); } catch (e) {}
  }

  function init() {
    takeSnapshot();
    var saved = 'hu';
    try { saved = localStorage.getItem('nmlang') || 'hu'; } catch (e) {}
    if (saved !== 'hu') apply(saved);
    else apply('hu'); // sets button state
    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.addEventListener('click', function () { apply(b.getAttribute('data-lang')); });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
